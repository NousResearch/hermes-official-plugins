function MemoryWikiPage() {
  const [route, go] = useHashRoute();
  const [locale, preference, select] = useLocale();
  const [search, setSearch] = useState("");
  // No locale key on views: switching language must not remount or refetch them.
  return <LocaleContext.Provider value={locale}><div lang={locale} className="space-y-6">
    <LanguagePicker preference={preference} select={select} />
    {route.view === "subject" ? <SubjectView slug={route.id} go={go} /> : route.view === "day" ? <DayView date={route.id} go={go} /> : <OverviewView go={go} search={search} setSearch={setSearch} />}
  </div></LocaleContext.Provider>;
}
window.__HERMES_PLUGINS__.register(PLUGIN_NAME, MemoryWikiPage);
